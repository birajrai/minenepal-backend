type BannerService struct {
	cache          *CacheService
	bannerCacheTTL time.Duration
}

func NewBannerService(cache *CacheService, bannerCacheTTL time.Duration) *BannerService {
	return &BannerService{
		cache:          cache,
		bannerCacheTTL: bannerCacheTTL,
	}
}

func (b *BannerService) GenerateBanner(status *types.ServerStatus) ([]byte, error) {
	width := 800
	height := 120
	iconSize := 64
	padding := 10

	img := image.NewRGBA(image.Rect(0, 0, width, height))

	for y := 0; y < height; y++ {
		for x := 0; x < width; x++ {
			ratio := float64(y) / float64(height)
			r := uint8(139*ratio + 101*(1-ratio))
			g := uint8(69*ratio + 33*(1-ratio))
			b := uint8(19*ratio + 19*(1-ratio))
			img.Set(x, y, color.RGBA{r, g, b, 255})
		}
	}

	if status.Icon != "" {
		iconData, err := b.loadIcon(status.Icon)
		if err == nil {
			iconBounds := iconData.Bounds()
			iconX := padding
			iconY := (height - iconBounds.Dy()) / 2

			for y := 0; y < iconBounds.Dy(); y++ {
				for x := 0; x < iconBounds.Dx(); x++ {
					if iconX+x < width && iconY+y < height {
						img.Set(iconX+x, iconY+y, iconData.At(x, y))
					}
				}
			}
		}
	}

	textX := iconSize + padding*2

	drawText(img, textX, 50, status.MOTD.Clean, 12)

	if status.Ping > 0 {
		pingColor := color.RGBA{0, 255, 0, 255}
		if status.Ping > 200 {
			pingColor = color.RGBA{255, 255, 0, 255}
		} else if status.Ping > 500 {
			pingColor = color.RGBA{255, 0, 0, 255}
		}
		drawTextAt(img, fmt.Sprintf("%dms", status.Ping), width-padding, 25, pingColor, 12)
	}

	playersText := fmt.Sprintf("%d/%d players", status.Players.Online, status.Players.Max)
	drawText(img, textX, 80, playersText, 12)

	if status.Version != "" {
		drawText(img, textX, 100, truncateString(status.Version, 30), 10)
	}

	var buf bytes.Buffer
	if err := png.Encode(&buf, img); err != nil {
		return nil, err
	}

	return buf.Bytes(), nil
}

func (b *BannerService) loadIcon(iconPath string) (image.Image, error) {
	fullPath := strings.TrimPrefix(iconPath, "/icons/")
	iconPath = filepath.Join(b.cache.cacheDir, "icons", fullPath)

	file, err := os.Open(iconPath)
	if err != nil {
		return nil, err
	}
	defer file.Close()

	return png.Decode(file)
}

func drawText(img *image.RGBA, x, y int, text string, size int) {
	drawTextAt(img, text, x, y, color.RGBA{255, 255, 255, 255}, size)
}

func drawTextAt(img *image.RGBA, text string, x, y int, col color.RGBA, size int) {
	runes := []rune(text)
	charWidth := size / 2
	startX := x

	for i, r := range runes {
		drawChar(img, r, startX+i*charWidth, y, col, size)
	}
}

func drawChar(img *image.RGBA, r rune, x, y int, col color.RGBA, size int) {
	font := getFont(r)
	for dy := 0; dy < 8 && dy < size; dy++ {
		for dx := 0; dx < 4 && dx < size/2; dx++ {
			if font[dy]&(1<<(4-1-dx)) != 0 {
				if x+dx < img.Bounds().Dx() && y+dy < img.Bounds().Dy() {
					img.Set(x+dx, y+dy, col)
				}
			}
		}
	}
}

